    var STORE_KEY = 'lang';
    var SKIP = '.pf-admin-toolbar, .pf-modal-overlay, .pf-admin-card-controls, #typing-text, .stat-number, .lang-toggle, script, style, noscript, textarea';
    var ATTRS = ['aria-label', 'title', 'alt', 'placeholder'];
    var MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

    function norm(s) { return String(s).replace(/\s+/g, ' ').trim(); }

    function fmtDate(d) {
        var p = d.split('/');
        if (p.length === 3) return parseInt(p[0], 10) + ' ' + MONTHS[parseInt(p[1], 10) - 1] + ' ' + p[2];
        if (p.length === 2) return MONTHS[parseInt(p[0], 10) - 1] + ' ' + p[1];
        return d;
    }

    // Retourne la traduction anglaise d'un texte français (ou null s'il n'y en a pas)
    function tr(str) {
        var n = norm(str);
        if (!n) return null;
        if (Object.prototype.hasOwnProperty.call(DICT, n)) return DICT[n];
        var m = n.match(/^Du (\d{1,2}\/\d{1,2}\/\d{4}|\d{1,2}\/\d{4}) au (\d{1,2}\/\d{1,2}\/\d{4}|\d{1,2}\/\d{4})$/);
        if (m) return 'From ' + fmtDate(m[1]) + ' to ' + fmtDate(m[2]);
        return null;
    }

    function detect() {
        try {
            var q = new URLSearchParams(window.location.search).get('lang');
            if (q === 'en' || q === 'fr') { localStorage.setItem(STORE_KEY, q); return q; }
            var saved = localStorage.getItem(STORE_KEY);
            if (saved === 'en' || saved === 'fr') return saved;
        } catch (e) { /* stockage indisponible */ }
        return 'fr';
    }

    var lang = detect();
    var info = new WeakMap();   // noeud texte -> { orig, out }
    var touched = [];           // noeuds modifiés (pour pouvoir revenir au français)

    function skipped(el) { return !el || (el.closest && el.closest(SKIP)); }

    function translateTextNode(node) {
        var par = node.parentElement;
        if (!par || skipped(par)) return;
        var cur = node.nodeValue;
        var rec = info.get(node);
        if (rec && cur === rec.out) return; // déjà traduit
        if (!cur || !cur.trim()) return;
        var t = tr(cur);
        if (t === null) return;
        var lead = cur.match(/^\s*/)[0];
        var trail = cur.match(/\s*$/)[0];
        var out = lead + t + trail;
        info.set(node, { orig: cur, out: out });
        touched.push(node);
        node.nodeValue = out;
    }

    function translateAttrs(el) {
        if (!el.getAttribute || skipped(el)) return;
        ATTRS.forEach(function (a) {
            if (!el.hasAttribute(a)) return;
            var key = 'data-i18n-orig-' + a;
            var orig = el.hasAttribute(key) ? el.getAttribute(key) : el.getAttribute(a);
            var t = tr(orig);
            if (t === null) return;
            if (!el.hasAttribute(key)) el.setAttribute(key, orig);
            el.setAttribute(a, t);
        });
    }

    function translateTree(root) {
        if (root.nodeType === 3) { translateTextNode(root); return; }
        if (root.nodeType !== 1) return;
        if (skipped(root)) return;
        translateAttrs(root);
        root.querySelectorAll('[aria-label],[title],[alt],[placeholder]').forEach(translateAttrs);
        var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        var n;
        while ((n = w.nextNode())) translateTextNode(n);
    }

    var META_SEL = 'meta[name="description"], meta[property="og:description"], meta[name="twitter:description"]';
    var origTitle = document.title;

    function applyHead() {
        var t = lang === 'en' ? tr(origTitle) : null;
        document.title = t !== null ? t : origTitle;
        document.querySelectorAll(META_SEL).forEach(function (m) {
            if (!m.hasAttribute('data-i18n-orig')) m.setAttribute('data-i18n-orig', m.getAttribute('content') || '');
            var o = m.getAttribute('data-i18n-orig');
            var tt = lang === 'en' ? tr(o) : null;
            m.setAttribute('content', tt !== null ? tt : o);
        });
    }

    function restoreFrench() {
        touched.forEach(function (node) {
            var rec = info.get(node);
            if (rec && node.nodeValue === rec.out) node.nodeValue = rec.orig;
        });
        touched = [];
        document.querySelectorAll('[data-i18n-orig-aria-label],[data-i18n-orig-title],[data-i18n-orig-alt],[data-i18n-orig-placeholder]').forEach(function (el) {
            ATTRS.forEach(function (a) {
                var key = 'data-i18n-orig-' + a;
                if (el.hasAttribute(key)) el.setAttribute(a, el.getAttribute(key));
            });
        });
    }

    function applyAll() {
        document.documentElement.setAttribute('lang', lang);
        if (lang === 'en') translateTree(document.body);
        else restoreFrench();
        applyHead();
    }

    // --- Contenu ajouté dynamiquement (fenêtres de détails, cartes recréées par le panneau admin...) ---
    var observer = new MutationObserver(function (muts) {
        if (lang !== 'en') return;
        muts.forEach(function (m) {
            m.addedNodes.forEach(function (n) { translateTree(n); });
        });
    });

    // --- Bouton FR / EN ---
    var btn = null;
    function updateButton() {
        if (!btn) return;
        btn.querySelectorAll('.lang-opt').forEach(function (s) {
            s.classList.toggle('active', s.getAttribute('data-l') === lang);
        });
        btn.setAttribute('aria-label', lang === 'fr' ? 'Changer la langue (Français → English)' : 'Change language (English → Français)');
        btn.setAttribute('title', lang === 'fr' ? 'Switch to English' : 'Passer en français');
    }

    function mountButton() {
        var nav = document.getElementById('navbar');
        if (!nav || document.getElementById('lang-toggle')) return;
        btn = document.createElement('button');
        btn.id = 'lang-toggle';
        btn.type = 'button';
        btn.className = 'lang-toggle';
        btn.innerHTML = '<span class="lang-opt" data-l="fr">FR</span><span class="lang-sep">/</span><span class="lang-opt" data-l="en">EN</span>';
        var themeBtn = document.getElementById('theme-toggle');
        if (themeBtn && themeBtn.parentNode === nav) nav.insertBefore(btn, themeBtn.nextSibling);
        else nav.insertBefore(btn, nav.firstChild);
        btn.addEventListener('click', function () { setLang(lang === 'fr' ? 'en' : 'fr'); });
        updateButton();
    }

    function setLang(l) {
        if (l !== 'fr' && l !== 'en') return;
        lang = l;
        try { localStorage.setItem(STORE_KEY, l); } catch (e) { /* ignore */ }
        applyAll();
        updateButton();
        window.dispatchEvent(new CustomEvent('langchange', { detail: l }));
    }

    window.I18N = {
        get lang() { return lang; },
        setLang: setLang,
        // traduit un texte français si l'anglais est actif
        t: function (s) {
            if (lang !== 'en') return s;
            var r = tr(s);
            return r === null ? s : r;
        }
    };

    function init() {
        mountButton();
        applyAll();
        updateButton();
        observer.observe(document.body, { childList: true, subtree: true });
    }

    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
    else init();
